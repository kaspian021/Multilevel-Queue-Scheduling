def _model_rows():
    rows = model_rows()
    out = []
    for r in rows:
        starv = r[5]
        starv = (starv.replace("none", "هیچ‌کس")
                      .replace("**all of them**", "**همهٔ آن‌ها**")
                      .replace("P", "فرایند "))
        out.append([r[0], r[1], r[2],
                    "برقرار" if r[3] == "holds" else "**نقض‌شده**",
                    "بله" if r[4] == "yes" else "**خیر**",
                    starv,
                    "بله" if r[6] == "yes" else "خیر"])
    return out


