def _m(scn, algo, key):
    return MM[f"{scn}|{algo}"][key]


def _pct(x):
    return f"{100 * x:.2f}"


def _scn_rows():
    names = {"A_fair": "منصفانه (A)", "B_stress": "تحت‌فشار (B)",
             "C_aperiodic": "ناپریودیک (C)", "D_overload": "بار اضافی (D)"}
    rows = []
    for s in ("A_fair", "B_stress", "C_aperiodic", "D_overload"):
        rows.append([names[s], _pct(MM[f"{s}|EDF"]["utilization"]) + "٪",
                     str(SC[s]["hyperperiod"]),
                     str(_m(s, "EDF", "deadline_misses")),
                     str(_m(s, "RM", "deadline_misses")),
                     str(_m(s, "MLQ", "deadline_misses"))])
    return rows


def _metric_rows(key, fmt="{:.3f}"):
    names = {"A_fair": "منصفانه (A)", "B_stress": "تحت‌فشار (B)",
             "C_aperiodic": "ناپریودیک (C)", "D_overload": "بار اضافی (D)"}
    rows = []
    for s in ("A_fair", "B_stress", "C_aperiodic", "D_overload"):
        rows.append([names[s]]
                    + [fmt.format(_m(s, a, key)) for a in ("EDF", "RM", "MLQ")])
    return rows


def _bucket_rows():
    rows = []
    for name in sorted(FS["buckets"]):
        b = FS["buckets"][name]
        if b["n"] == 0:
            continue
        rows.append([name, str(b["n"]),
                     f"{100.0 * b['rm'] / b['n']:.1f}٪",
                     f"{100.0 * b['edf'] / b['n']:.1f}٪"])
    return rows


def _model_rows():
    order = ("dekker", "peterson", "lock_variable", "flag_spin", "tas",
             "semaphore_binary", "semaphore_wrong_order", "monitor_mesa")
    families = {"software": "نرم‌افزاری", "broken": "معیوب",
                "hardware": "سخت‌افزاری", "primitive": "پریمتیو",
                "monitor": "مانیتور"}
    rows = []
    for n in order:
        r = M4[n]
        rows.append([f"`{n}`", families[r["family"]], str(r["states"]),
                     "برقرار" if r["mutual_exclusion"] else "**نقض‌شده**",
                     "بله" if r["deadlock_free"] else "**خیر**",
                     "بله" if all(r["starvation_free"].values()) else "**خیر**"])
    return rows


